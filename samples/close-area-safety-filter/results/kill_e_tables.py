"""Part e tables: per-cell collision % and reached % with 95 % Wilson intervals, held-out seeds.

python results/kill_e_tables.py      # reads kill_d_unsensed_on_0.json (seed 0) and kill_e_*_unsensed_on_*.json
Writes results/kill_e_tables.md. Stdlib only. All inputs are synthetic.
"""
import glob
import json
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ARMS = ("F2", "F3", "F4@eps_m=0.2", "F5")
CASES = ("none", "jump", "bias", "dropout", "uwb_nlos", "both")
Z = 1.959964


def wilson(k, n):
    if n == 0:
        return (float("nan"), float("nan"))
    p = k / n
    d = 1 + Z * Z / n
    c = (p + Z * Z / (2 * n)) / d
    h = Z * math.sqrt(p * (1 - p) / n + Z * Z / (4 * n * n)) / d
    return (100 * max(0.0, c - h), 100 * min(1.0, c + h))


def load(path, arms=ARMS):
    d = json.load(open(path))
    cells = {}
    for r in d["runs"]:
        if r["arm"] in arms:
            c = cells.setdefault((r["arm"], r["case"]), [0, 0, 0])
            c[0] += 1
            c[1] += int(bool(r["collision"]))
            c[2] += int(bool(r["reached"]))
    return d, cells


def fmt(c):
    n, k, rc = c
    lo, hi = wilson(k, n)
    return f"{k}/{n} = {100 * k / n:.1f} [{lo:.1f}, {hi:.1f}] / {100 * rc / n:.0f}"


def table(cells, title):
    out = [f"### {title}", "", "Collisions/runs = collision % [95 % Wilson interval] / reached %, unsensed obstacles on.", "",
           "| arm | " + " | ".join(CASES) + " |", "|---|" + "---|" * len(CASES)]
    for a in ARMS:
        out.append(f"| {a} | " + " | ".join(fmt(cells[(a, c)]) if (a, c) in cells else "-" for c in CASES) + " |")
    out.append("")
    out.append("Reach ratio vs F2 (reached / F2 reached), same case:")
    out.append("")
    out.append("| arm | " + " | ".join(CASES[:4]) + " |")
    out.append("|---|" + "---|" * 4)
    for a in ARMS[1:]:
        cols = []
        for c in CASES[:4]:
            f2, x = cells.get(("F2", c)), cells.get((a, c))
            cols.append("-" if not f2 or not x or f2[2] == 0 else f"{x[2] / f2[2]:.2f}")
        out.append(f"| {a} | " + " | ".join(cols) + " |")
    return out + [""]


def pooled_line(cells, a):
    tot = [0, 0, 0]
    for c in CASES:
        if (a, c) in cells:
            tot = [t + v for t, v in zip(tot, cells[(a, c)])]
    lo, hi = wilson(tot[1], tot[0])
    return f"| {a} | {tot[0]} | {tot[1]} | {100 * tot[1] / tot[0]:.2f} [{lo:.2f}, {hi:.2f}] |"


def main():
    md = ["# Part e: held-out seeds (synthetic)", "",
          "Generated by `python results/kill_e_tables.py`. Seed 0 is `kill_d_unsensed_on_0.json` (part d, "
          "where F4's 0.2 m was swept); seeds 1-2 and the u_trap / narrow_gap families are held out. "
          "All inputs synthetic.", ""]
    seeds = {}
    _, seeds[0] = load(os.path.join(HERE, "kill_d_unsensed_on_0.json"))
    for p in sorted(glob.glob(os.path.join(HERE, "kill_e_unsensed_on_*.json"))):
        d, cells = load(p)
        seeds[d["seed"]] = cells
    for s in sorted(seeds):
        md += table(seeds[s], f"random family, seed {s}, 100 layouts" + (" (tuning seed)" if s == 0 else " (held out)"))
    comb = {}
    for s, cells in seeds.items():
        for key, v in cells.items():
            comb[key] = [a + b for a, b in zip(comb.get(key, [0, 0, 0]), v)]
    md += table(comb, f"random family, seeds {', '.join(map(str, sorted(seeds)))} combined")
    held = {}
    for s, cells in seeds.items():
        if s != 0:
            for key, v in cells.items():
                held[key] = [a + b for a, b in zip(held.get(key, [0, 0, 0]), v)]
    if held:
        md += table(held, "random family, held-out seeds only (1, 2) combined")
    fams = {}
    for fam in ("u_trap", "narrow_gap"):
        for p in sorted(glob.glob(os.path.join(HERE, f"kill_e_{fam}_unsensed_on_*.json"))):
            d, cells = load(p)
            fams[fam] = cells
            md += table(cells, f"{fam} family, seed {d['seed']}, {d['layouts']} layouts (held out)")
    md += ["### All cases pooled per arm", "",
           "Collisions over every case the arm ran (F5 includes uwb_nlos and both).", ""]
    for name, cells in [("random seeds 0-2", comb), ("random seeds 1-2", held)] + list(fams.items()):
        md += [f"{name}:", "", "| arm | runs | collisions | collision % [95 % Wilson] |", "|---|---|---|---|"]
        md += [pooled_line(cells, a) for a in ARMS] + [""]
    md += ["### Every collision of F4@eps_m=0.2 and F5", "",
           "| file | arm | case | layout | hit unsensed | F4 slack steps | F5 ended in hover | max pose err m |",
           "|---|---|---|---|---|---|---|---|"]
    files = [os.path.join(HERE, "kill_d_unsensed_on_0.json")] + sorted(glob.glob(os.path.join(HERE, "kill_e_*unsensed_on_*.json")))
    for p in files:
        for r in json.load(open(p))["runs"]:
            if r["collision"] and r["arm"] in ("F4@eps_m=0.2", "F5"):
                fs = r.get("filter_stats") or {}
                md.append(f"| {os.path.basename(p)} | {r['arm']} | {r['case']} | {r['index']} | {r['hit_unsensed']} "
                          f"| {fs.get('slack_steps', '-') if r['arm'] != 'F5' else '-'} "
                          f"| {r.get('ended_in_hover') if r['arm'] == 'F5' else '-'} | {r['max_pose_error_m']} |")
    md.append("")
    out = os.path.join(HERE, "kill_e_tables.md")
    open(out, "w").write("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
