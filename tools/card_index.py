#!/usr/bin/env python3
"""Generate docs/integration-cards/README.md: every card grouped by its repo's primary concept.

Reads each card's title, lead paragraph, License row and <!-- about: --> marker, plus the repo
record (concepts, hackathon_fit, GitHub last push) from index/records.jsonl. Output is
deterministic for a given input. `--check` exits 1 if the committed README is out of date.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CARDS = ROOT / "docs" / "integration-cards"
OUT = CARDS / "README.md"
RECORDS = ROOT / "index" / "records.jsonl"
ABOUT_RE = re.compile(r"<!--\s*about:\s*([^>]+?)\s*-->")
PURPOSE_MAX = 170  # chars of the card's lead sentence shown in the table
LICENSE_MAX = 40
FIT_ORDER = {"high": 0, "medium": 1, "low": 2}


def load_records():
    recs = {}
    with RECORDS.open() as fh:
        for line in fh:
            if line.strip():
                r = json.loads(line)
                recs[r["id"]] = r
    return recs


def cell(text):
    return re.sub(r"\s+", " ", text.replace("|", "/")).strip()


def plain(text):
    text = re.sub(r"!?\[([^\]]*)\]\([^)]*\)", r"\1", text)
    return re.sub(r"[*_]{2,}", "", text)


def clip(text, limit):
    if len(text) <= limit:
        return text
    cut = text[:limit].rsplit(" ", 1)[0].rstrip(",;:(")
    return cut + "..."


def lead_sentence(body):
    for block in re.split(r"\n\s*\n", re.sub(r"<!--.*?-->", "", body, flags=re.S)):
        b = block.strip()
        if not b or b.startswith(("#", "|", "```", "<")):
            continue
        b = re.sub(r"^\**One-line:?\**:?\s*", "", plain(b.replace("\n", " ")))
        first = re.split(r"(?<=[a-z0-9)`])\.\s+(?=[A-Z`])|;\s+", b, maxsplit=1)[0].rstrip(".")
        first = clip(cell(first), PURPOSE_MAX)
        return first[:1].upper() + first[1:]
    return ""


def license_short(body):
    m = re.search(r"^\|\s*License\s*\|\s*(.+?)\s*\|\s*$", body, flags=re.M)
    if not m:
        return "not stated"
    text = plain(m.group(1)).replace("`", "")
    text = re.sub(r"^(?:Code|Repo code|LICENSE(?:\.md|\.txt)?(?: file)?)\s*:\s*", "", text)
    short = re.split(r"\s\(|\.\s|\.$|;\s|,\s", text, maxsplit=1)[0]
    return clip(cell(short), LICENSE_MAX) or "see card"


def card_rows(recs):
    rows, unknown = [], []
    for f in sorted(CARDS.glob("*.md")):
        if f.name == "README.md" or f.name.startswith("_"):
            continue
        body = f.read_text()
        ids = [x.strip() for m in ABOUT_RE.finditer(body) for x in m.group(1).split(",")]
        rec = next((recs[i] for i in ids if i in recs), None)
        if rec is None:
            unknown.append(f.name)
            continue
        title = next((ln[2:] for ln in body.splitlines() if ln.startswith("# ")), f.stem)
        title = re.sub(r"\s+-\s+integration card\s*$", "", title, flags=re.I).strip()
        gh = rec.get("github") or {}
        push = (gh.get("pushed_at") or "")[:10] or "not tracked"
        if gh.get("archived"):
            push += " (archived)"
        concepts = rec.get("concepts") or ["concept:uncategorised"]
        rows.append({
            "file": f.name, "title": cell(title), "id": rec["id"], "primary": concepts[0],
            "others": concepts[1:], "fit": rec.get("hackathon_fit") or "-",
            "license": license_short(body), "push": push, "purpose": lead_sentence(body),
        })
    return rows, unknown


def render(rows, recs):
    concept_order = [i for i, r in recs.items() if r["kind"] == "concept"]
    rank = {c: n for n, c in enumerate(concept_order)}
    groups = {}
    for r in rows:
        groups.setdefault(r["primary"], []).append(r)
    ordered = sorted(groups, key=lambda c: (rank.get(c, len(rank)), c))

    def cname(c):
        return recs[c]["name"] if c in recs else c.split(":", 1)[-1]

    def short(c):
        return c.split(":", 1)[-1]

    out = [
        "# Integration cards",
        "",
        "<!-- Generated by tools/card_index.py from the cards and index/records.jsonl. Do not edit by hand:",
        "     run `python3 tools/card_index.py` after adding a card or rebuilding the index. -->",
        "",
        f"{len(rows)} cards, one per repo: install, wiring, gotchas, license. Cards were read from "
        "source, docs and issues, not run, unless the card says so. Grouped by the repo's primary "
        "concept in the index; \"Also\" lists its other concepts. Fit is the index's hackathon fit. "
        "Last push is the GitHub API value stored in the index at build time, not a release date: "
        "check releases on GitHub before you pin a version. License is the card's License row, "
        "shortened; read the card for caveats.",
        "",
        "Per-capability picks (default and alternative): [reference-stacks.md](../reference-stacks.md). "
        "Narrative notes per writing batch, with the top gotcha of each card: "
        + ", ".join(f"[{p.stem.lstrip('_')}]({p.name})" for p in sorted(CARDS.glob("_index-*.md"))) + ".",
        "",
        "## Contents",
        "",
    ]
    out += [f"- [{cname(c)}](#{anchor(cname(c))}) ({len(groups[c])})" for c in ordered]
    out.append("")
    for c in ordered:
        out += [f"## {cname(c)}", "",
                "| Card | Fit | License | Last push | Purpose | Also |",
                "|---|---|---|---|---|---|"]
        for r in sorted(groups[c], key=lambda r: (FIT_ORDER.get(r["fit"], 3), r["title"].lower())):
            also = ", ".join(short(x) for x in r["others"]) or "-"
            out.append(f"| [{r['title']}]({r['file']}) | {r['fit']} | {r['license']} | {r['push']} | "
                       f"{r['purpose']} | {also} |")
        out.append("")
    return "\n".join(out)


def anchor(heading):
    a = re.sub(r"[^\w\s-]", "", heading.lower()).strip()
    return re.sub(r"\s", "-", a)


def main(argv):
    recs = load_records()
    rows, unknown = card_rows(recs)
    if unknown:
        print("cards whose about ids are not in the index: " + ", ".join(unknown), file=sys.stderr)
        return 1
    text = render(rows, recs)
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run python3 tools/card_index.py", file=sys.stderr)
            return 1
        print(f"{OUT.relative_to(ROOT)} up to date ({len(rows)} cards)")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(rows)} cards)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
